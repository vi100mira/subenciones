import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = path.join(root, "supabase", "bootstrap", "empty-project-bootstrap.manifest.json");
const migrationsRoot = path.join(root, "supabase", "migrations");
const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const files = manifest.segments.flatMap((segment) => segment.files);

for (const file of files) {
  if (!fs.existsSync(path.join(migrationsRoot, file))) throw new Error(`Falta la migración declarada: ${file}`);
}
for (const excluded of manifest.excludedMigrations) {
  if (files.includes(excluded.file)) throw new Error(`La migración excluida está incluida: ${excluded.file}`);
}

const preflight = `do $$
begin
  if exists (select 1 from pg_tables where schemaname = 'public') then
    raise exception 'Bootstrap cancelado: public ya contiene tablas. No es seguro reaplicar el esquema.';
  end if;
end;
$$;`;

const chunks = files.map((file) => {
  const sql = fs.readFileSync(path.join(migrationsRoot, file), "utf8").trim();
  return `\n-- BEGIN MIGRATION ${file}\n${sql}\n-- END MIGRATION ${file}`;
});

process.stdout.write([
  "-- Generated by scripts/emit-empty-project-bootstrap.mjs.",
  "-- This script performs no network call and does not write a migration-history row.",
  "-- Run only through an approved migration path, then reconcile migration history explicitly.",
  "begin;",
  preflight,
  ...chunks,
  "commit;",
  ""
].join("\n"));
